//literals

class literals{
	public static void main(String a[])
	{
		int num1 = 0b1001;
		int num2 = 0x23E;
		int num3 = 10_00_00_000;
		double num4 = 23;
		System.out.println(num1);
		System.out.println(num2);
		System.out.println(num3);
		System.out.println(num4);
		char c = 'a';
		System.out.println(c);
		c++;
		System.out.println(c);
	}
}