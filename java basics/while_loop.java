// Loops
// while loop
public class while_loop
{
	public static void main(String arg[])
	{
		int i =1;
		System.out.println("we are going inside loop");
		while(i <= 4)
		{
			System.out.println("hiii" + i);
			i++;
		}
		System.out.println("byee we are out of the while loop");
	}
}
